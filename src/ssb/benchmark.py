# Scoring
# --------------------------------------------------------------------------


@dataclass
class ClassResult:
    perturbation: str
    family: str
    n: int
    hits: int

    @property
    def recall(self) -> float:
        return self.hits / self.n if self.n else 0.0


@dataclass
class Scorecard:
    matcher: str
    threshold: float
    generated_at: str
    overall_recall: float
    overall_precision: float
    false_positive_rate: float
    by_class: list
    manifest: Manifest

    def to_dict(self) -> dict:
        return {
            "matcher": self.matcher,
            "threshold": self.threshold,
            "generated_at": self.generated_at,
            "overall_recall": round(self.overall_recall, 4),
            "overall_precision": round(self.overall_precision, 4),
            "false_positive_rate": round(self.false_positive_rate, 4),
            "by_class": [
                {
                    "perturbation": c.perturbation,
                    "family": c.family,
                    "n": c.n,
                    "hits": c.hits,
                    "recall": round(c.recall, 4),
                }
                for c in self.by_class
            ],
            "manifest": asdict(self.manifest),
        }

    @classmethod
    def from_dict(cls, payload: dict) -> Scorecard:
        by_class = [
            ClassResult(c["perturbation"], c["family"], c["n"], c["hits"])
            for c in payload["by_class"]
        ]
        return cls(
            matcher=payload["matcher"],
            threshold=payload["threshold"],
            generated_at=payload["generated_at"],
            overall_recall=payload["overall_recall"],
            overall_precision=payload["overall_precision"],
            false_positive_rate=payload["false_positive_rate"],
            by_class=by_class,
            manifest=Manifest(**payload["manifest"]),
        )

    @classmethod
    def from_json(cls, path) -> Scorecard:
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
        return cls.from_dict(payload)


@dataclass
class CaseOutcome:
    """Pre-threshold match result for a single benchmark case."""

    expected_entity_id: str
    perturbation: str
    family: str
    best_id: str
    best_score: float


def evaluate_cases(bench: Benchmark, matcher: Callable) -> list:
    """Run ``matcher`` once per case and return the best candidate match."""
    outcomes = []
    for case in bench.cases:
        best_id, best_score = None, 0.0
        for entity_id, names in bench.candidates.items():
            for cand in names:
                s = matcher(case.query, cand)
                if s > best_score:
                    best_id, best_score = entity_id, s
        outcomes.append(
            CaseOutcome(
                expected_entity_id=case.expected_entity_id,
                perturbation=case.perturbation,
                family=case.family,
                best_id=best_id,
                best_score=best_score,
            )
        )
    return outcomes


def _metrics_at_threshold(outcomes: list, threshold: float) -> tuple:
    buckets = {}
    tp = fn = fp = tn = 0

    for outcome in outcomes:
        fired = outcome.best_score >= threshold
        if outcome.expected_entity_id is not None:
            key = (outcome.perturbation, outcome.family)
            bucket = buckets.setdefault(
                key,
                ClassResult(outcome.perturbation, outcome.family, 0, 0),
            )
            bucket.n += 1
            if fired and outcome.best_id == outcome.expected_entity_id:
                bucket.hits += 1
                tp += 1
            else:
                fn += 1
        elif fired:
            fp += 1
        else:
            tn += 1

    recall = tp / (tp + fn) if (tp + fn) else 0.0
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    fpr = fp / (fp + tn) if (fp + tn) else 0.0
    by_class = sorted(buckets.values(), key=lambda c: (c.family, c.recall))
    return recall, precision, fpr, by_class


def score(bench: Benchmark, matcher: Callable, threshold: float = 0.85, matcher_name=None) -> Scorecard:
    """Run ``matcher`` over every case and produce a scorecard.

    A positive case is a hit when the highest-scoring candidate at or above
    ``threshold`` belongs to the expected entity. Matching some *other* listed
    entity is a failure, not a success. A negative case is a false positive when
    any candidate scores at or above ``threshold``.
    """
    name = matcher_name or getattr(matcher, "name", type(matcher).__name__)
    outcomes = evaluate_cases(bench, matcher)
    recall, precision, fpr, by_class = _metrics_at_threshold(outcomes, threshold)
    return Scorecard(
        matcher=name,
        threshold=threshold,
        generated_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        overall_recall=recall,
        overall_precision=precision,
        false_positive_rate=fpr,
        by_class=by_class,
        manifest=bench.manifest,
    )


def format_scorecard(sc: Scorecard) -> str:
    """Render a scorecard as a plain-text report."""
    lines = []
    a = lines.append
    a("=" * 72)
    a("  SANCTIONS SCREENING BENCHMARK — SCORECARD")
    a("=" * 72)
    a(f"  Matcher            {sc.matcher}")
    a(f"  Threshold          {sc.threshold}")
    a(f"  List source        {sc.manifest.list_source} (retrieved {sc.manifest.list_retrieved_at})")
    a(f"  Entities / cases   {sc.manifest.entity_count} / {sc.manifest.case_count}")
    a(f"  Positives / negs   {sc.manifest.positive_count} / {sc.manifest.negative_count}")
    a("")
    a(f"  Overall recall     {sc.overall_recall:6.1%}")
    a(f"  Overall precision  {sc.overall_precision:6.1%}")
    a(f"  False positive rt  {sc.false_positive_rate:6.1%}   (against synthetic negatives)")
    a("")
    a("-" * 72)
    a(f"  {'PERTURBATION':<22}{'FAMILY':<14}{'N':>6}{'HITS':>7}{'RECALL':>9}")
    a("-" * 72)
    current_family = None
    for c in sc.by_class:
        if c.family != current_family:
            if current_family is not None:
                a("")
            current_family = c.family
        flag = "  <-- blind spot" if c.recall < 0.5 else ""
        a(f"  {c.perturbation:<22}{c.family:<14}{c.n:>6}{c.hits:>7}{c.recall:>8.1%}{flag}")
    a("-" * 72)
    a("")
    a("  Read the class-wise profile, not the headline. A low score on an")
    a("  ADVERSARIAL class is an evasion exposure. A low score on a BENIGN class")
    a("  is a data-quality false-negative exposure. They have different owners")
    a("  and different fixes.")
    a("")
    a("  The precision figure measures discrimination against structurally")
    a("  adjacent synthetic strings. It is NOT a production alert-volume estimate.")
    a("=" * 72)
    return "\n".join(lines)


