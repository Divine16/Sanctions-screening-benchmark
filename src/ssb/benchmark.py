"""
Benchmark construction and scoring.

A benchmark is a manifest plus a set of cases. Each case is a query string with a
label: either the entity it should match (a positive) or ``None`` (a negative
control). Scoring runs a matcher over every case against the candidate pool and
reports, per perturbation class, whether the correct entity was recovered.

The headline number is deliberately NOT a single figure. The useful output is the
class-wise recall profile: it tells you which specific kinds of variation an
engine is blind to, which is actionable, where an aggregate F1 is not.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable

from . import negatives as neg
from . import perturb
from .sources import Entity, ListSnapshot

SCHEMA_VERSION = "1.0"


@dataclass
class Case:
    query: str
    expected_entity_id: str
    perturbation: str
    family: str
    source_name: str = None


@dataclass
class Manifest:
    schema_version: str
    generated_at: str
    list_source: str
    list_retrieved_at: str
    list_endpoint: str
    entity_count: int
    case_count: int
    positive_count: int
    negative_count: int
    seed: int
    perturbations: list
    max_per_class: int
    notes: str = (
        "Generated by sanctions-screening-benchmark. No sanctions list data is "
        "redistributed in this manifest beyond the derived test strings."
    )


@dataclass
class Benchmark:
    manifest: Manifest
    cases: list
    candidates: dict = field(default_factory=dict)

    def to_json(self, path) -> None:
        payload = {
            "manifest": asdict(self.manifest),
            "candidates": self.candidates,
            "cases": [asdict(c) for c in self.cases],
        }
        Path(path).write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")

    @classmethod
    def from_json(cls, path):
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
        return cls(
            manifest=Manifest(**payload["manifest"]),
            cases=[Case(**c) for c in payload["cases"]],
            candidates=payload["candidates"],
        )


def build(
    snapshot: ListSnapshot,
    limit=250,
    seed: int = 0,
    only=None,
    max_per_class: int = 2,
    individuals_only: bool = True,
    negatives_per_class: int = 1,
) -> Benchmark:
    """Construct a benchmark from a list snapshot."""
    pool = snapshot.individuals() if individuals_only else snapshot.entities
    pool = [e for e in pool if len(e.primary_name.split()) >= 2]
    pool.sort(key=lambda e: e.entity_id)
    if limit is not None:
        pool = pool[:limit]

    candidates = {e.entity_id: e.all_names() for e in pool}
    listed_index = snapshot.name_index()

    cases = []

    # --- positives --------------------------------------------------------
    for e in pool:
        for variant in perturb.apply_all(
            e.primary_name, e.entity_id, seed=seed, only=only, max_per_class=max_per_class
        ):
            if variant.text.casefold() == e.primary_name.casefold():
                continue
            cases.append(
                Case(
                    query=variant.text,
                    expected_entity_id=e.entity_id,
                    perturbation=variant.perturbation,
                    family=variant.family,
                    source_name=e.primary_name,
                )
            )

    # --- negative controls ------------------------------------------------
    names = [e.primary_name for e in pool]
    for n in neg.generate(names, seed=seed, per_class=negatives_per_class, listed_index=listed_index):
        cases.append(
            Case(
                query=n.text,
                expected_entity_id=None,
                perturbation=n.negative_class,
                family="negative",
                source_name=n.derived_from[0] if n.derived_from else None,
            )
        )

    positives = sum(1 for c in cases if c.expected_entity_id is not None)
    manifest = Manifest(
        schema_version=SCHEMA_VERSION,
        generated_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        list_source=snapshot.source,
        list_retrieved_at=snapshot.retrieved_at,
        list_endpoint=snapshot.endpoint,
        entity_count=len(pool),
        case_count=len(cases),
        positive_count=positives,
        negative_count=len(cases) - positives,
        seed=seed,
        perturbations=sorted(only if only is not None else list(perturb.REGISTRY)),
        max_per_class=max_per_class,
    )
    return Benchmark(manifest=manifest, cases=cases, candidates=candidates)


# --------------------------------------------------------------------------
# Scoring
# --------------------------------------------------------------------------


@dataclass
class ClassResult:
    perturbation: str
    family: str
    n: int
    hits: int

    @property
    def recall(self) -> float:
        return self.hits / self.n if self.n else 0.0


@dataclass
class Scorecard:
    matcher: str
    threshold: float
    generated_at: str
    overall_recall: float
    overall_precision: float
    false_positive_rate: float
    by_class: list
    manifest: Manifest

    def to_dict(self) -> dict:
        return {
            "matcher": self.matcher,
            "threshold": self.threshold,
            "generated_at": self.generated_at,
            "overall_recall": round(self.overall_recall, 4),
            "overall_precision": round(self.overall_precision, 4),
            "false_positive_rate": round(self.false_positive_rate, 4),
            "by_class": [
                {
                    "perturbation": c.perturbation,
                    "family": c.family,
                    "n": c.n,
                    "hits": c.hits,
                    "recall": round(c.recall, 4),
                }
                for c in self.by_class
            ],
            "manifest": asdict(self.manifest),
        }

    @classmethod
    def from_dict(cls, payload: dict) -> Scorecard:
        by_class = [
            ClassResult(c["perturbation"], c["family"], c["n"], c["hits"])
            for c in payload["by_class"]
        ]
        return cls(
            matcher=payload["matcher"],
            threshold=payload["threshold"],
            generated_at=payload["generated_at"],
            overall_recall=payload["overall_recall"],
            overall_precision=payload["overall_precision"],
            false_positive_rate=payload["false_positive_rate"],
            by_class=by_class,
            manifest=Manifest(**payload["manifest"]),
        )

    @classmethod
    def from_json(cls, path) -> Scorecard:
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
        return cls.from_dict(payload)


def score(bench: Benchmark, matcher: Callable, threshold: float = 0.85, matcher_name=None) -> Scorecard:
    """Run ``matcher`` over every case and produce a scorecard.

    A positive case is a hit when the highest-scoring candidate at or above
    ``threshold`` belongs to the expected entity. Matching some *other* listed
    entity is a failure, not a success. A negative case is a false positive when
    any candidate scores at or above ``threshold``.
    """
    name = matcher_name or getattr(matcher, "name", type(matcher).__name__)

    buckets = {}
    tp = fn = fp = tn = 0

    for case in bench.cases:
        best_id, best_score = None, 0.0
        for entity_id, names in bench.candidates.items():
            for cand in names:
                s = matcher(case.query, cand)
                if s > best_score:
                    best_id, best_score = entity_id, s

        fired = best_score >= threshold

        if case.expected_entity_id is not None:
            key = (case.perturbation, case.family)
            b = buckets.setdefault(key, ClassResult(case.perturbation, case.family, 0, 0))
            b.n += 1
            if fired and best_id == case.expected_entity_id:
                b.hits += 1
                tp += 1
            else:
                fn += 1
        else:
            if fired:
                fp += 1
            else:
                tn += 1

    recall = tp / (tp + fn) if (tp + fn) else 0.0
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    fpr = fp / (fp + tn) if (fp + tn) else 0.0

    by_class = sorted(buckets.values(), key=lambda c: (c.family, c.recall))
    return Scorecard(
        matcher=name,
        threshold=threshold,
        generated_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        overall_recall=recall,
        overall_precision=precision,
        false_positive_rate=fpr,
        by_class=by_class,
        manifest=bench.manifest,
    )


def format_scorecard(sc: Scorecard) -> str:
    """Render a scorecard as a plain-text report."""
    lines = []
    a = lines.append
    a("=" * 72)
    a("  SANCTIONS SCREENING BENCHMARK — SCORECARD")
    a("=" * 72)
    a(f"  Matcher            {sc.matcher}")
    a(f"  Threshold          {sc.threshold}")
    a(f"  List source        {sc.manifest.list_source} (retrieved {sc.manifest.list_retrieved_at})")
    a(f"  Entities / cases   {sc.manifest.entity_count} / {sc.manifest.case_count}")
    a(f"  Positives / negs   {sc.manifest.positive_count} / {sc.manifest.negative_count}")
    a("")
    a(f"  Overall recall     {sc.overall_recall:6.1%}")
    a(f"  Overall precision  {sc.overall_precision:6.1%}")
    a(f"  False positive rt  {sc.false_positive_rate:6.1%}   (against synthetic negatives)")
    a("")
    a("-" * 72)
    a(f"  {'PERTURBATION':<22}{'FAMILY':<14}{'N':>6}{'HITS':>7}{'RECALL':>9}")
    a("-" * 72)
    current_family = None
    for c in sc.by_class:
        if c.family != current_family:
            if current_family is not None:
                a("")
            current_family = c.family
        flag = "  <-- blind spot" if c.recall < 0.5 else ""
        a(f"  {c.perturbation:<22}{c.family:<14}{c.n:>6}{c.hits:>7}{c.recall:>8.1%}{flag}")
    a("-" * 72)
    a("")
    a("  Read the class-wise profile, not the headline. A low score on an")
    a("  ADVERSARIAL class is an evasion exposure. A low score on a BENIGN class")
    a("  is a data-quality false-negative exposure. They have different owners")
    a("  and different fixes.")
    a("")
    a("  The precision figure measures discrimination against structurally")
    a("  adjacent synthetic strings. It is NOT a production alert-volume estimate.")
    a("=" * 72)
    return "\n".join(lines)


